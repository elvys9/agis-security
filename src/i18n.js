export function initialLanguage(storage = globalThis.localStorage) {
  try {
    const saved = storage?.getItem('threatlens.language') ?? storage?.getItem('aegis.language');
    if (messages[saved]) return saved;
  } catch { /* Storage can be unavailable in restricted browser previews. */ }
  return 'en';
}

export function translate(language, key, values = {}) {
  const template = messages[language]?.[key] ?? messages.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''));
}

export function formatNumber(language, value) {
  return new Intl.NumberFormat(languages.find(item => item.code === language)?.locale ?? 'en-US').format(Math.round(value || 0));
}

// The native scanner uses technical, stable strings. Paths, hashes and rule
// identifiers remain unchanged; only known user-facing phrases are translated.
export function translateEngineText(language, value) {
  const text = String(value ?? '');
  const t = (key, values) => translate(language, key, values);
  if (text.startsWith('Monitoraggio user-mode:')) return t('warningUserMode');
  if (text.startsWith('Database iniziale limitato')) return t('warningTestDb');
  if (text.startsWith('Minifilter, anti-exploit')) return t('warningUnavailable');
  if (text.startsWith('YARA non incluso:')) return t('warningYara');
  let match = /^Watcher: (\d+) eventi persi/.exec(text);
  if (match) return t('warningDropped', { count: match[1] });
  match = /^Monitoraggio: (\d+) analisi incomplete/.exec(text);
  if (match) return t('warningIncomplete', { count: match[1] });
  if (text.startsWith('Feed HTTPS e chiave Ed25519')) return t('updateNotConfigured');
  if (text.startsWith('Definizioni verificate e attivate')) return t('updateSuccess');
  if (text.startsWith('Nessun aggiornamento disponibile')) return t('updateNoChange');
  if (text.startsWith('Contenitore danneggiato:')) return text.replace('Contenitore danneggiato', t('damagedReason'));
  if (text.startsWith('High entropy executable section ')) return text.replace('High entropy executable section', t('highEntropy'));
  if (text.startsWith('YARA skipped: file exceeds')) return t('yaraSkipped');
  if (text.startsWith('YARA disabled in this build')) return t('yaraDisabled');
  if (text.startsWith('PE incomplete:')) return text.replace('PE incomplete', t('peIncomplete'));
  if (text.startsWith('YARA incomplete:')) return text.replace('YARA incomplete', t('yaraIncomplete'));
  return text;
}
